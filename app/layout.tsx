import { QueryProvider } from "@/features/(app)/(ui)/_providers/QueryProvider";
import { AuthProvider } from "@/features/auth/components/provider/AuthProvider";
import { getCurrentUser } from "@/features/auth/lib/session";
import { cn } from "@/lib/utils/cn";
import type { Metadata } from "next";
import { Inter, Outfit, Plus_Jakarta_Sans } from "next/font/google";
import "../public/assets/style/style.css";
import "./globals.css";

const outfit = Outfit({
    weight: ["100", "200", "300", "400", "500", "600", "700", "800"],
    variable: "--font-nunito",
    subsets: ["latin"],
});

const plusJakarta = Plus_Jakarta_Sans({
    weight: ["200", "300", "400", "500", "600", "700", "800"],
    variable: "--font-cal-sans",
});

const inter = Inter({
    weight: ["100", "200", "300", "400", "500", "600", "700", "800", "900"],
    variable: "--inter-sans",
});

export const metadata: Metadata = {
    title: "DateApp - fullstack",
    description: "This app generated by nextjs.",
};

export default async function RootLayout({ children }: LayoutProps<"/">) {
    const user = await getCurrentUser();

    return (
        <html
            lang="en"
            className={cn(
                "dark",
                "h-full",
                "antialiased",
                outfit.variable,
                plusJakarta.variable,
                inter.variable,
            )}>
            <body className="min-h-full">
                <QueryProvider>
                    <AuthProvider user={user}>{children}</AuthProvider>
                </QueryProvider>
            </body>
        </html>
    );
}
